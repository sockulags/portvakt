export const MESSAGES: Readonly<Record<Locale, Messages>> = { sv, en };

/** A message with a singular and a plural form (`{count}` is filled in). */
export interface Plural {
  readonly one: string;
  readonly other: string;
}

/** The form of `forms` for `count`, with `{count}` and any other placeholders filled. */
export function plural(
  forms: Plural,
  count: number,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return format(count === 1 ? forms.one : forms.other, { count, ...values });
}

/** Fills `{name}` placeholders. */
export function format(
  template: string,
  values: Readonly<Record<string, string | number>>,
): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    values[key] === undefined ? match : String(values[key]),
  );
}

const STORAGE_KEY = "pv-admin-locale";

/**
 * Swedish unless the administrator chose English (stored). The browser's languages are not
 * consulted: the portal is Swedish first.
 */
export function pickLocale(stored: string | null): Locale {
  return stored === "en" ? "en" : DEFAULT_LOCALE;
}

export function storedLocale(): string | null {
  try {
    return window.localStorage.getItem(STORAGE_KEY);
  } catch {
    return null;
  }
}

export function storeLocale(locale: Locale): void {
  try {
    window.localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    // Private mode: the choice lasts for this page only.
  }
}

/** Dates and times in the chosen language. */
/** The time of day of an ISO instant (HH:MM, 24 hours). */
export function formatTime(iso: string, locale: Locale): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return "–";
  return new Intl.DateTimeFormat(locale === "sv" ? "sv-SE" : "en-GB", {
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).format(date);
}

export function formatDate(
  iso: string | null | undefined,
  locale: Locale,
  withTime = false,
): string {
  if (iso === null || iso === undefined) return "–";
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return "–";
  return new Intl.DateTimeFormat(locale === "sv" ? "sv-SE" : "en-GB", {
    dateStyle: "medium",
    ...(withTime ? { timeStyle: "short" } : {}),
  }).format(date);
}

export interface I18n {
  readonly locale: Locale;
  readonly t: Messages;
  readonly setLocale: (locale: Locale) => void;
}

export const I18nContext = createContext<I18n>({
  locale: DEFAULT_LOCALE,
  t: sv,
  setLocale: () => undefined,
});

export const useI18n = (): I18n => useContext(I18nContext);
