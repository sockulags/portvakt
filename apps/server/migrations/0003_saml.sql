-- Upstream SAML 2.0 following the Swedish eID Framework (M3b). See docs/plan.md, "SAML upstream
-- (Swedish eID Framework)", and CLAUDE.md.
--
-- * login_methods gains `protocol` (existing rows are OIDC); the OIDC columns issuer and
--   client_id become NULL for SAML methods, whose configuration lives in login_method_saml.
-- * login_method_saml: the IdP (entityID, metadata URL or inline XML, optional metadata signing
--   certificate, refresh interval), the last good metadata (refreshed by a scheduled job; a
--   login never fetches it while a cached copy exists), the requested LoA and entity
--   categories, the attribute mapping and the subject source used for identity linking.
-- * saml_sp_keys: the SP's signing and encryption key pairs with self-signed certificates,
--   generated by Portvakt. Private keys are SecretBox envelopes (context
--   `saml_sp_key:<id>:private_key`). Per purpose: one `active`, optionally one `next` (both
--   published in SP metadata during a rotation overlap) and one `previous` (no longer
--   published, still accepted for decryption until the next rotation).
-- * saml_replay_cache: assertion IDs (as SHA-256, base64url) seen at the ACS, insert-once until
--   they expire.
-- * applications may be allowed the extra scope `hsa` (claims hsa_id, org_affiliation).
-- * federation_states also holds pending SAML AuthnRequests: the RelayState is the state (only
--   its hash is the key) and the request ID is what the response's InResponseTo must name.

ALTER TABLE login_methods
  ADD COLUMN protocol text NOT NULL DEFAULT 'oidc' CHECK (protocol IN ('oidc', 'saml')),
  ALTER COLUMN issuer DROP NOT NULL,
  ALTER COLUMN client_id DROP NOT NULL,
  ADD CONSTRAINT login_methods_protocol_columns CHECK (
    CASE protocol
      WHEN 'oidc' THEN issuer IS NOT NULL AND client_id IS NOT NULL
      ELSE issuer IS NULL AND client_id IS NULL AND client_secret_encrypted IS NULL
           AND client_key_kid IS NULL
    END
  ),
  -- Target of login_method_saml's foreign key: SAML settings attach to SAML methods only.
  ADD CONSTRAINT login_methods_protocol_key UNIQUE (tenant_id, id, protocol);

CREATE TABLE login_method_saml (
  tenant_id                    uuid NOT NULL,
  login_method_id              uuid NOT NULL,
  protocol                     text NOT NULL DEFAULT 'saml' CHECK (protocol = 'saml'),
  idp_entity_id                text NOT NULL CHECK (length(idp_entity_id) BETWEEN 1 AND 1024),
  metadata_url                 text CHECK (metadata_url ~ '^https?://' AND length(metadata_url) <= 2048),
  metadata_xml                 text CHECK (length(metadata_xml) BETWEEN 1 AND 10485760),
  metadata_signing_certificate text CHECK (metadata_signing_certificate LIKE '-----BEGIN CERTIFICATE-----%'),
  -- An explicit decision to use a metadata URL without a signing certificate (refused in
  -- production otherwise); audited when saved.
  allow_unsigned_metadata      boolean NOT NULL DEFAULT false,
  metadata_refresh_seconds     integer NOT NULL DEFAULT 3600
                               CHECK (metadata_refresh_seconds BETWEEN 300 AND 604800),
  -- Last good metadata: what Portvakt uses of the IdP's EntityDescriptor (endpoints, signing
  -- certificates, scopes), taken from the signature-checked document; JSON, validated on read.
  metadata_cache               jsonb CHECK (jsonb_typeof(metadata_cache) = 'object'),
  metadata_cached_at           timestamptz,
  metadata_valid_until         timestamptz,
  -- Last refresh attempt, and the reason code of the last failed one (cleared on success).
  metadata_checked_at          timestamptz,
  metadata_error               text CHECK (metadata_error ~ '^[a-z_]{1,64}$'),
  requested_loa                text[] NOT NULL CHECK (cardinality(requested_loa) BETWEEN 1 AND 20),
  authn_context_comparison     text NOT NULL DEFAULT 'exact'
                               CHECK (authn_context_comparison IN ('exact', 'minimum')),
  entity_categories            text[] NOT NULL DEFAULT '{}' CHECK (cardinality(entity_categories) <= 50),
  requested_attributes         jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(requested_attributes) = 'array'),
  subject_source               text NOT NULL
                               CHECK (subject_source IN ('personalIdentityNumber', 'prid', 'employeeHsaId', 'nameId')),
  attribute_mapping            jsonb NOT NULL CHECK (jsonb_typeof(attribute_mapping) = 'object'),
  authn_request_binding        text NOT NULL DEFAULT 'redirect'
                               CHECK (authn_request_binding IN ('redirect', 'post')),
  require_encrypted_assertions boolean NOT NULL DEFAULT true,
  require_signed_response      boolean NOT NULL DEFAULT true,
  sign_metadata                boolean NOT NULL DEFAULT false,
  clock_skew_seconds           integer NOT NULL DEFAULT 60 CHECK (clock_skew_seconds BETWEEN 0 AND 300),
  trust_email                  boolean NOT NULL DEFAULT false,
  -- Refuse AES-CBC content encryption (only AES-GCM).
  require_gcm                  boolean NOT NULL DEFAULT false,
  -- mdui:UIInfo of the SP metadata (DisplayName, Description, Logo), validated on read.
  ui_info                      jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(ui_info) = 'object'),
  -- orgAffiliation scopes (organisation numbers) accepted besides the IdP's shibmd:Scope.
  org_affiliation_scopes       text[] NOT NULL DEFAULT '{}'
                               CHECK (cardinality(org_affiliation_scopes) <= 50),
  PRIMARY KEY (tenant_id, login_method_id),
  UNIQUE (login_method_id),
  CONSTRAINT login_method_saml_metadata_source CHECK ((metadata_url IS NULL) <> (metadata_xml IS NULL)),
  CONSTRAINT login_method_saml_unsigned_metadata CHECK (
    NOT allow_unsigned_metadata OR (metadata_url IS NOT NULL AND metadata_signing_certificate IS NULL)
  ),
  FOREIGN KEY (tenant_id, login_method_id, protocol)
    REFERENCES login_methods (tenant_id, id, protocol) ON DELETE CASCADE
);
CREATE INDEX login_method_saml_refresh_idx ON login_method_saml (metadata_checked_at NULLS FIRST)
  WHERE metadata_url IS NOT NULL;

CREATE TABLE saml_sp_keys (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id             uuid NOT NULL,
  login_method_id       uuid NOT NULL,
  purpose               text NOT NULL CHECK (purpose IN ('signing', 'encryption')),
  state                 text NOT NULL CHECK (state IN ('next', 'active', 'previous')),
  certificate           text NOT NULL CHECK (certificate LIKE '-----BEGIN CERTIFICATE-----%'),
  private_key_encrypted text NOT NULL CHECK (private_key_encrypted LIKE 'pv1.%'),
  not_after             timestamptz NOT NULL,
  created_at            timestamptz NOT NULL DEFAULT now(),
  state_changed_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, login_method_id, purpose, state),
  FOREIGN KEY (tenant_id, login_method_id) REFERENCES login_methods (tenant_id, id) ON DELETE CASCADE
);
CREATE INDEX saml_sp_keys_expiry_idx ON saml_sp_keys (tenant_id, not_after) WHERE state <> 'previous';

CREATE TABLE saml_replay_cache (
  tenant_id       uuid NOT NULL,
  login_method_id uuid NOT NULL,
  assertion_id    text NOT NULL CHECK (length(assertion_id) BETWEEN 1 AND 256),
  expires_at      timestamptz NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, login_method_id, assertion_id),
  FOREIGN KEY (tenant_id, login_method_id) REFERENCES login_methods (tenant_id, id) ON DELETE CASCADE
);
CREATE INDEX saml_replay_cache_expires_idx ON saml_replay_cache (expires_at);

ALTER TABLE federation_states
  ADD COLUMN protocol text NOT NULL DEFAULT 'oidc' CHECK (protocol IN ('oidc', 'saml')),
  ALTER COLUMN code_verifier_encrypted DROP NOT NULL,
  ALTER COLUMN nonce DROP NOT NULL,
  -- The AuthnRequest ID: the response's InResponseTo must name it.
  ADD COLUMN saml_request_id text CHECK (saml_request_id ~ '^[A-Za-z_][A-Za-z0-9._-]{0,127}$'),
  -- What the request asked for (ForceAuthn, LoA, comparison); protocol values only.
  ADD COLUMN saml_request jsonb CHECK (jsonb_typeof(saml_request) = 'object'),
  -- PrincipalSelection personal identity number (step-up of a known person), encrypted.
  ADD COLUMN saml_principal_encrypted text CHECK (saml_principal_encrypted LIKE 'pv1.%'),
  -- The HTTP-POST binding page of the request was rendered (it is rendered once only).
  ADD COLUMN saml_post_rendered_at timestamptz,
  ADD CONSTRAINT federation_states_protocol_columns CHECK (
    CASE protocol
      WHEN 'oidc' THEN code_verifier_encrypted IS NOT NULL AND nonce IS NOT NULL
                       AND saml_request_id IS NULL AND saml_request IS NULL
      ELSE saml_request_id IS NOT NULL AND saml_request IS NOT NULL
           AND code_verifier_encrypted IS NULL AND nonce IS NULL
    END
  );
CREATE UNIQUE INDEX federation_states_saml_request_idx
  ON federation_states (tenant_id, login_method_id, saml_request_id) WHERE saml_request_id IS NOT NULL;

ALTER TABLE applications
  DROP CONSTRAINT applications_allowed_extra_scopes_check,
  ADD CONSTRAINT applications_allowed_extra_scopes_check
    CHECK (allowed_extra_scopes <@ ARRAY['pin', 'hsa']::text[]);
