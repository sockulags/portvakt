/** Production: every redirect URI is https. */
function checkRedirectUris(
  deps: AdminDeps,
  field: string,
  uris: readonly string[] | undefined,
): void {
  if (uris === undefined || !deps.config.isProduction) return;
  uris.forEach((uri, index) => {
    if (!uri.startsWith("https://"))
      throw fieldError(`${field}.${index}`, "must use https in production");
  });
}

/** The client authentication to store, with a generated secret for the secret methods. */
function clientAuthFor(input: z.output<typeof clientAuthInput>): {
  auth: ClientAuthInput;
  secret: string | undefined;
} {
  if (input.method === "private_key_jwt") return { auth: input, secret: undefined };
  const secret = generateClientSecret();
  return { auth: { method: input.method, clientSecret: secret }, secret };
}

/** portvakt-admin must stay usable: enabled, its roles declared, no representation. */
function guardAdminApplication(application: Application, body: z.output<typeof updateBody>): void {
  if (application.clientId !== ADMIN_CLIENT_ID) return;
  if (body.enabled === false) throw new ApiError("self_lockout");
  if (body.roles !== undefined) {
    const names = new Set(body.roles.map((role) => role.role));
    if (!ADMIN_ROLES.every((role) => names.has(role.role))) throw new ApiError("self_lockout");
  }
  if (body.representationMode !== undefined && body.representationMode !== "none") {
    throw fieldError("representationMode", "the admin portal never represents");
  }
}

async function replaceDeclarations(
  tx: Tx,
  application: Application,
  body: z.output<typeof updateBody>,
): Promise<void> {
  if (body.roles !== undefined) {
    const wanted = new Map(body.roles.map((role) => [role.role, role.description]));
    for (const role of application.roles) {
      if (!wanted.has(role.role)) await tx.repos.applications.removeRole(application.id, role.role);
    }
    for (const [role, description] of wanted) {
      await tx.repos.applications.declareRole(application.id, role, description);
    }
  }
  if (body.attributeKeys !== undefined) {
    const wanted = new Map(body.attributeKeys.map((key) => [key.key, key.description]));
    for (const key of application.attributeKeys) {
      if (!wanted.has(key.key))
        await tx.repos.applications.removeAttributeKey(application.id, key.key);
    }
    for (const [key, description] of wanted) {
      await tx.repos.applications.declareAttributeKey(application.id, key, description);
    }
  }
}

async function lockedApplication(
  tx: Tx,
  id: string,
  ifMatch: string | undefined,
): Promise<Application> {
  await lockRow(tx, "applications", "id = $1", [id]);
  const current = await tx.repos.applications.findById(id);
  if (current === null) throw notFound();
  requireMatch(ifMatch, applicationView(current).etag);
  return current;
}

async function recordApplication(
  tx: Tx,
  caller: Caller,
  action: "admin.application.create" | "admin.application.update",
  before: Application | null,
  after: Application,
  secretChanged: boolean,
): Promise<void> {
  await tx.record({
    action,
    tenantId: null,
    actor: actorOf(caller),
    subject: { type: "application", id: after.id },
    details: {
      actorTenantId: caller.tenant.id,
      changes: diff(
        before === null ? {} : audited(before),
        audited(after, secretChanged),
        REDACTED,
      ),
    },
  });
}

export function applicationRoutes(deps: AdminDeps): AdminRoute[] {
  return [
    route({
      method: "get",
      path: "/applications",
      operationId: "listApplications",
      summary: "Every registered application (global)",
      tag: "Applications",
      platformOnly: true,
      response: listOf(applicationSchema),
      handler: async () => ({
        body: { items: (await deps.repos.applications.list()).map(applicationView) },
      }),
    }),
    route({
      method: "post",
      path: "/applications",
      operationId: "createApplication",
      summary: "Register an application",
      tag: "Applications",
      platformOnly: true,
      status: 201,
      body: createBody,
      response: applicationWithSecretSchema,
      errors: ["conflict"],
      handler: async ({ caller, body }) => {
        checkRedirectUris(deps, "redirectUris", body.redirectUris);
        checkRedirectUris(deps, "postLogoutRedirectUris", body.postLogoutRedirectUris);
        const { auth, secret } = clientAuthFor(body.clientAuth);
        const application = await inTransaction(deps, async (tx) => {
          const created = await tx.repos.applications.create({ ...body, clientAuth: auth });
          await recordApplication(
            tx,
            caller,
            "admin.application.create",
            null,
            created,
            secret !== undefined,
          );
          return created;
        });
        return {
          status: 201,
          body: {
            application: applicationView(application),
            ...(secret === undefined ? {} : { clientSecret: secret }),
          },
        };
      },
    }),
    route({
      method: "get",
      path: "/applications/{applicationId}",
      operationId: "getApplication",
      summary: "An application",
      tag: "Applications",
      platformOnly: true,
      params: applicationParams,
      response: applicationSchema,
      handler: async ({ params }) => {
        const application = await deps.repos.applications.findById(params.applicationId);
        if (application === null) throw notFound();
        return { body: applicationView(application) };
      },
    }),
    route({
      method: "patch",
      path: "/applications/{applicationId}",
      operationId: "updateApplication",
      summary: "Change an application",
      tag: "Applications",
      platformOnly: true,
      ifMatch: true,
      params: applicationParams,
      body: updateBody,
      response: applicationWithSecretSchema,
      errors: ["self_lockout"],
      handler: async ({ caller, params, body, ifMatch }) => {
        checkRedirectUris(deps, "redirectUris", body.redirectUris);
        checkRedirectUris(deps, "postLogoutRedirectUris", body.postLogoutRedirectUris);
        let secret: string | undefined;
        const application = await inTransaction(deps, async (tx) => {
          const current = await lockedApplication(tx, params.applicationId, ifMatch);
          guardAdminApplication(current, body);
          const { roles: _roles, attributeKeys: _keys, clientAuth, ...patch } = body;
          void _roles;
          void _keys;
          let auth: ClientAuthInput | undefined;
          if (clientAuth !== undefined) {
            const next = clientAuthFor(clientAuth);
            auth = next.auth;
            secret = next.secret;
          }
          await tx.repos.applications.update(current.id, {
            ...patch,
            ...(auth === undefined ? {} : { clientAuth: auth }),
          });
          await replaceDeclarations(tx, current, body);
          const updated = await tx.repos.applications.findById(current.id);
          if (updated === null) throw notFound();
          await recordApplication(
            tx,
            caller,
            "admin.application.update",
            current,
            updated,
            secret !== undefined,
          );
          return updated;
        });
        return {
          body: {
            application: applicationView(application),
            ...(secret === undefined ? {} : { clientSecret: secret }),
          },
        };
      },
    }),
    route({
      method: "post",
      path: "/applications/{applicationId}/rotate-secret",
      operationId: "rotateApplicationSecret",
      summary: "Replace the client secret; the new secret is returned once",
      description:
        "The old secret stops working at once. Deploy the new secret to the application first " +
        "where possible, or rotate during a maintenance window.",
      tag: "Applications",
      platformOnly: true,
      ifMatch: true,
      params: applicationParams,
      response: applicationWithSecretSchema,
      handler: async ({ caller, params, ifMatch }) => {
        const secret = generateClientSecret();
        const application = await inTransaction(deps, async (tx) => {
          const current = await lockedApplication(tx, params.applicationId, ifMatch);
          if (current.clientAuth.method === "private_key_jwt") {
            throw fieldError("clientAuth", "the application authenticates with private_key_jwt");
          }
          const updated = await tx.repos.applications.update(current.id, {
            clientAuth: { method: current.clientAuth.method, clientSecret: secret },
          });
          await tx.record({
            action: "admin.application.secret_rotate",
            tenantId: null,
            actor: actorOf(caller),
            subject: { type: "application", id: current.id },
            details: { actorTenantId: caller.tenant.id },
          });
          return updated;
        });
        return { body: { application: applicationView(application), clientSecret: secret } };
      },
    }),
    route({
      method: "get",
      path: "/tenants/{tenantId}/applications",
      operationId: "listTenantApplications",
      summary: "The applications attached to the tenant",
      tag: "Applications",
      params: tenantParams,
      response: listOf(tenantApplicationSchema),
      handler: async ({ caller, params }) => {
        const tenant = await targetTenant(deps, caller, params.tenantId);
        const entries = await deps.repos.applications.listForTenant(tenant.id);
        return { body: { items: entries.map(tenantApplicationView) } };
      },
    }),
    route({
      method: "put",
      path: "/tenants/{tenantId}/applications/{applicationId}",
      operationId: "attachTenantApplication",
      summary: "Attach an application to the tenant and enable it",
      tag: "Applications",
      platformOnly: true,
      params: tenantApplicationParams,
      response: tenantApplicationSchema,
      handler: async ({ caller, params }) => {
        const tenant = await targetTenant(deps, caller, params.tenantId);
        const application = await deps.repos.applications.findById(params.applicationId);
        if (application === null) throw notFound();
        const entry = await inTransaction(deps, async (tx) => {
          const before = (await tx.repos.applications.listForTenant(tenant.id)).find(
            (item) => item.application.id === application.id,
          );
          if (before?.enabled !== true) {
            await tx.repos.applications.enableForTenant(tenant.id, application.id);
            await tx.record({
              action:
                before === undefined
                  ? "admin.tenant_application.attach"
                  : "admin.tenant_application.update",
              tenantId: tenant.id,
              actor: actorOf(caller),
              subject: { type: "application", id: application.id },
              details:
                before === undefined
                  ? { actorTenantId: caller.tenant.id, applicationId: application.id }
                  : {
                      actorTenantId: caller.tenant.id,
                      applicationId: application.id,
                      changes: { enabled: { from: false, to: true } },
                    },
            });
          }
          const after = (await tx.repos.applications.listForTenant(tenant.id)).find(
            (item) => item.application.id === application.id,
          );
          if (after === undefined) throw notFound();
          return { after, created: before === undefined };
        });
        return { status: entry.created ? 201 : 200, body: tenantApplicationView(entry.after) };
      },
    }),
    route({
      method: "patch",
      path: "/tenants/{tenantId}/applications/{applicationId}",
      operationId: "updateTenantApplication",
      summary: "Enable or disable an attached application in the tenant",
      tag: "Applications",
      ifMatch: true,
      params: tenantApplicationParams,
      body: strictBody({ enabled: z.boolean() }),
      response: tenantApplicationSchema,
      errors: ["self_lockout"],
      handler: async ({ caller, params, body, ifMatch }) => {
        const tenant = await targetTenant(deps, caller, params.tenantId);
        const entry = await inTransaction(deps, async (tx) => {
          await lockRow(tx, "tenant_applications", "tenant_id = $1 AND application_id = $2", [
            tenant.id,
            params.applicationId,
          ]);
          const current = (await tx.repos.applications.listForTenant(tenant.id)).find(
            (item) => item.application.id === params.applicationId,
          );
          if (current === undefined) throw notFound();
          requireMatch(ifMatch, tenantApplicationView(current).etag);
          if (
            !body.enabled &&
            current.application.clientId === ADMIN_CLIENT_ID &&
            tenant.id === caller.tenant.id
          ) {
            throw new ApiError("self_lockout");
          }
          if (current.enabled === body.enabled) return current;
          if (body.enabled)
            await tx.repos.applications.enableForTenant(tenant.id, params.applicationId);
          else {
            await tx.repos.applications.disableForTenant(tenant.id, params.applicationId);
            // The application's grants in the tenant end now; enabling it again starts afresh.
            await endLogins(
              tx,
              caller,
              tenant.id,
              { clientId: current.application.clientId },
              {
                reason: "application_disabled",
                subject: { type: "application", id: params.applicationId },
                clientId: current.application.clientId,
              },
            );
          }
          await assertPlatformReachable(tx, tenant);
          await tx.record({
            action: "admin.tenant_application.update",
            tenantId: tenant.id,
            actor: actorOf(caller),
            subject: { type: "application", id: params.applicationId },
            details: {
              actorTenantId: caller.tenant.id,
              applicationId: params.applicationId,
              changes: diff({ enabled: current.enabled }, { enabled: body.enabled }),
            },
          });
          const after = (await tx.repos.applications.listForTenant(tenant.id)).find(
            (item) => item.application.id === params.applicationId,
          );
          if (after === undefined) throw notFound();
          return after;
        });
        return { body: tenantApplicationView(entry) };
      },
    }),
    route({
      method: "post",
      path: "/applications/{applicationId}/removal-impact",
      operationId: "getRemovalImpact",
      summary: "What removing roles or attribute keys from an application would delete",
      description:
        "Counts in every tenant: assignments (also pending) and rules of the roles, assignments " +
        "of the attribute keys. Show them before a PATCH that drops declarations.",
      tag: "Applications",
      platformOnly: true,
      params: applicationParams,
      body: strictBody({
        roles: z.array(z.string().max(100)).max(200).default([]),
        attributeKeys: z.array(z.string().max(64)).max(200).default([]),
      }),
      response: usageSchema,
      handler: async ({ params, body }) => {
        const application = await deps.repos.applications.findById(params.applicationId);
        if (application === null) throw notFound();
        const usage = await deps.repos.stats.applicationUsage(application.id, {
          tenantId: null,
          roles: body.roles,
          keys: body.attributeKeys,
        });
        return { body: { ...usage, grantLimits: 0 } };
      },
    }),
    route({
      method: "get",
      path: "/tenants/{tenantId}/applications/{applicationId}/usage",
      operationId: "getTenantApplicationUsage",
      summary: "What detaching the application from the tenant would delete",
      tag: "Applications",
      platformOnly: true,
      params: tenantApplicationParams,
      response: usageSchema,
      handler: async ({ caller, params }) => {
        const tenant = await targetTenant(deps, caller, params.tenantId);
        const attached = (await deps.repos.applications.listForTenant(tenant.id)).some(
          (entry) => entry.application.id === params.applicationId,
        );
        if (!attached) throw notFound();
        return {
          body: await deps.repos.stats.applicationUsage(params.applicationId, {
            tenantId: tenant.id,
            roles: null,
            keys: null,
          }),
        };
      },
    }),
    route({
      method: "post",
      path: "/tenants/{tenantId}/applications/{applicationId}/detach",
      operationId: "detachTenantApplication",
      summary:
        "Detach an application from the tenant, deleting its assignments, rules and grant limits there",
      description:
        "`confirmClientId` must repeat the application's client_id (a typed confirmation). " +
        "Disabling keeps everything and is reversible; detaching is not.",
      tag: "Applications",
      platformOnly: true,
      ifMatch: true,
      params: tenantApplicationParams,
      body: strictBody({ confirmClientId: z.string().min(1).max(128) }),
      response: usageSchema,
      errors: ["self_lockout"],
      handler: async ({ caller, params, body, ifMatch }) => {
        const tenant = await targetTenant(deps, caller, params.tenantId);
        const removed = await inTransaction(deps, async (tx) => {
          await lockRow(tx, "tenant_applications", "tenant_id = $1 AND application_id = $2", [
            tenant.id,
            params.applicationId,
          ]);
          const current = (await tx.repos.applications.listForTenant(tenant.id)).find(
            (item) => item.application.id === params.applicationId,
          );
          if (current === undefined) throw notFound();
          requireMatch(ifMatch, tenantApplicationView(current).etag);
          if (body.confirmClientId !== current.application.clientId) {
            throw fieldError("confirmClientId", "must repeat the application's client_id");
          }
          if (current.application.clientId === ADMIN_CLIENT_ID && tenant.id === caller.tenant.id) {
            throw new ApiError("self_lockout");
          }
          const usage = await tx.repos.stats.applicationUsage(params.applicationId, {
            tenantId: tenant.id,
            roles: null,
            keys: null,
          });
          await tx.repos.applications.removeFromTenant(tenant.id, params.applicationId);
          await assertPlatformReachable(tx, tenant);
          await endLogins(
            tx,
            caller,
            tenant.id,
            { clientId: current.application.clientId },
            {
              reason: "application_detached",
              subject: { type: "application", id: params.applicationId },
              clientId: current.application.clientId,
            },
          );
          await tx.record({
            action: "admin.tenant_application.detach",
            tenantId: tenant.id,
            actor: actorOf(caller),
            subject: { type: "application", id: params.applicationId },
            details: {
              actorTenantId: caller.tenant.id,
              applicationId: params.applicationId,
              removed: usage,
            },
          });
          return usage;
        });
        return { body: removed };
      },
    }),
  ];
}
