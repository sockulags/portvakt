/** Role rules: (login method key, upstream group, role), for every demo application. */
const ROLE_RULES = [
  { method: "entra", group: "grp-handlaggare", role: "handlaggare" },
  { method: "entra", group: "grp-admins", role: "admin" },
  { method: "siths", group: "sara@2321000016", role: "lakare" },
] as const;

export async function seedDev(target: SeedTarget, options: DevSeedOptions): Promise<SeedReport> {
  const { repos, samlAdmin } = target;
  const changes: string[] = [];
  const generatedSecrets: Record<string, string> = {};

  let tenant = await repos.tenants.findBySlug(DEMO_TENANT_SLUG);
  if (tenant === null) {
    tenant = await repos.tenants.create({ slug: DEMO_TENANT_SLUG, name: "Demo kommun" });
    changes.push(`tenant ${DEMO_TENANT_SLUG} created`);
  }
  const tenantId = tenant.id;

  const applications: Record<string, { id: string; created: boolean }> = {};
  const byClientId: Record<string, Application> = {};
  for (const service of options.services) {
    const { application, created, secret } = await ensureApplication(repos, service);
    applications[service.clientId] = { id: application.id, created };
    byClientId[service.clientId] = application;
    if (secret !== undefined) generatedSecrets[service.clientId] = secret;
    if (created) changes.push(`application ${service.clientId} created`);
    const attached = (await repos.applications.listForTenant(tenantId)).find(
      (entry) => entry.application.id === application.id,
    );
    if (service.enabled && attached?.enabled !== true) {
      await repos.applications.enableForTenant(tenantId, application.id);
      changes.push(`application ${service.clientId} enabled in ${DEMO_TENANT_SLUG}`);
    } else if (!service.enabled && attached?.enabled !== false) {
      // Attached but disabled: sign-in is refused until it is enabled (e2e scenario 3).
      await repos.applications.enableForTenant(tenantId, application.id);
      await repos.applications.disableForTenant(tenantId, application.id);
      changes.push(`application ${service.clientId} disabled in ${DEMO_TENANT_SLUG}`);
    }
  }

  const existing = await repos.loginMethods.list(tenantId);
  const methodIds: Record<string, string> = {};
  for (const { key, ...input } of oidcMethods(options)) {
    const found = existing.find((method) => method.displayName === input.displayName);
    let method: LoginMethod;
    if (found === undefined) {
      method = await repos.loginMethods.create(tenantId, input);
      changes.push(`login method ${input.displayName} created`);
    } else {
      method = await repos.loginMethods.update(tenantId, found.id, input);
    }
    methodIds[key] = method.id;
  }
  for (const { key, ...input } of samlMethods(options)) {
    const found = existing.find((method) => method.displayName === input.displayName);
    let method: LoginMethod;
    if (found === undefined) {
      method = await samlAdmin.create(tenantId, input);
      changes.push(`login method ${input.displayName} created`);
    } else {
      // Naming the metadata URL again fetches the IdP's current metadata (new mock keys).
      method = await samlAdmin.update(tenantId, found.id, {
        displayName: input.displayName,
        assertedAcr: input.assertedAcr,
        sessionPolicy: input.sessionPolicy,
        linkByPin: input.linkByPin ?? false,
        trustPinForRepresentation: input.trustPinForRepresentation ?? false,
        saml: {
          idpEntityId: input.saml.idpEntityId,
          metadataUrl: input.saml.metadataUrl ?? null,
          allowUnsignedMetadata: input.saml.allowUnsignedMetadata ?? false,
        },
      });
    }
    methodIds[key] = method.id;
  }

  for (const service of options.services) {
    const application = byClientId[service.clientId]!;
    const rules = await repos.access.listRules(tenantId, { applicationId: application.id });
    for (const rule of ROLE_RULES) {
      const loginMethodId = methodIds[rule.method]!;
      const present = rules.some(
        (existingRule) =>
          existingRule.loginMethodId === loginMethodId &&
          existingRule.groupValue === rule.group &&
          existingRule.role === rule.role,
      );
      if (present) continue;
      await repos.access.createRule(tenantId, {
        applicationId: application.id,
        loginMethodId,
        groupValue: rule.group,
        role: rule.role,
      });
      changes.push(`rule ${rule.group} -> ${rule.role} for ${service.clientId}`);
    }
  }

  for (const party of [
    { type: "organisation" as const, ...SEED_ORGANISATION },
    { type: "person" as const, ...SEED_PERSON_PARTY },
  ]) {
    let found = await repos.parties.findByIdentifier(tenantId, party.type, party.identifier);
    if (found === null) {
      found = await repos.parties.create(tenantId, party);
      changes.push(`party ${party.displayName} created`);
    }
    const grants = await repos.grants.listForParty(tenantId, found.id);
    if (!grants.some((grant) => grant.revokedAt === null)) {
      await repos.grants.create(tenantId, {
        agent: { pin: SEED_AGENT_PIN },
        partyId: found.id,
        allApplications: true,
      });
      changes.push(`representation grant for ${party.displayName} created`);
    }
  }

  if (options.isolationTenant !== undefined) {
    await seedIsolationTenant(repos, options.isolationTenant, byClientId, changes);
  }

  if (options.admin !== undefined) {
    await seedAdmin(repos, options, tenantId, methodIds.entra!, changes);
  }

  return { tenant, applications, generatedSecrets, loginMethods: methodIds, changes };
}

/**
 * The admin portal (apps/admin on :3400): the `system` tenant with a Mock Entra login method,
 * `portvakt-admin` enabled in `system` and `demo`, Erik (`erik-admin`) as platform admin and
 * Anna (`anna-handlaggare`) as tenant admin of `demo`, as pending assignments by upstream subject
 * until they first sign in (what the bootstrap and the admin API do in production).
 */
async function seedAdmin(
  repos: Repositories,
  options: DevSeedOptions,
  demoTenantId: string,
  demoEntraId: string,
  changes: string[],
): Promise<void> {
  const admin = options.admin!;
  let system = await repos.tenants.findBySlug(SYSTEM_TENANT_SLUG);
  if (system === null) {
    system = await repos.tenants.create({ slug: SYSTEM_TENANT_SLUG, name: "Portvakt" });
    changes.push(`tenant ${SYSTEM_TENANT_SLUG} created`);
  }
  const { application, created } = await ensureAdminApplication(
    repos,
    admin.publicUrl,
    admin.clientSecret,
  );
  if (created) changes.push(`application ${ADMIN_CLIENT_ID} created`);
  for (const tenantId of [system.id, demoTenantId]) {
    const attached = (await repos.applications.listForTenant(tenantId)).find(
      (entry) => entry.application.id === application.id,
    );
    if (attached?.enabled !== true) {
      await repos.applications.enableForTenant(tenantId, application.id);
      changes.push(
        `application ${ADMIN_CLIENT_ID} enabled in ${tenantId === system.id ? SYSTEM_TENANT_SLUG : DEMO_TENANT_SLUG}`,
      );
    }
  }
  const systemMethods = await repos.loginMethods.list(system.id);
  const input = {
    ...oidcMethods(options).find((method) => method.key === "entra")!,
    displayName: "Mock Entra (administratörer)",
    homeRealmDomains: [],
  };
  const { key: _key, ...methodInput } = input;
  void _key;
  const found = systemMethods.find((method) => method.displayName === methodInput.displayName);
  const systemEntra =
    found === undefined
      ? await repos.loginMethods.create(system.id, methodInput)
      : await repos.loginMethods.update(system.id, found.id, methodInput);
  if (found === undefined) changes.push(`login method ${methodInput.displayName} created`);

  const grants: readonly [string, string, string, string][] = [
    [system.id, systemEntra.id, SEED_PLATFORM_ADMIN_OID, PLATFORM_ADMIN_ROLE],
    [demoTenantId, demoEntraId, SEED_TENANT_ADMIN_OID, TENANT_ADMIN_ROLE],
  ];
  for (const [tenantId, loginMethodId, subject, role] of grants) {
    const target = { loginMethodId, subject };
    const persons = await repos.persons.matchPendingTarget(tenantId, target);
    if (persons.length > 0) {
      for (const personId of persons) {
        await repos.access.assignRole(tenantId, { personId, applicationId: application.id, role });
      }
      continue;
    }
    const pending = await repos.pending.listRoles(tenantId, { applicationId: application.id });
    const present = pending.some(
      (item) =>
        item.role === role &&
        item.target.kind === "identity" &&
        item.target.loginMethodId === loginMethodId &&
        item.target.subject === subject,
    );
    if (!present) {
      await repos.pending.createRole(tenantId, { applicationId: application.id, role, target });
      changes.push(`pending ${role} assignment created`);
    }
  }
}

async function seedIsolationTenant(
  repos: Repositories,
  isolation: NonNullable<DevSeedOptions["isolationTenant"]>,
  byClientId: Readonly<Record<string, Application>>,
  changes: string[],
): Promise<void> {
  let tenant = await repos.tenants.findBySlug(isolation.slug);
  if (tenant === null) {
    tenant = await repos.tenants.create({ slug: isolation.slug, name: isolation.name });
    changes.push(`tenant ${isolation.slug} created`);
  }
  const attached = await repos.applications.listForTenant(tenant.id);
  for (const clientId of isolation.clientIds) {
    const application = byClientId[clientId];
    if (application === undefined) throw new Error(`isolation tenant: ${clientId} is not seeded`);
    const entry = attached.find((item) => item.application.id === application.id);
    if (entry?.enabled !== true) {
      await repos.applications.enableForTenant(tenant.id, application.id);
      changes.push(`application ${clientId} enabled in ${isolation.slug}`);
    }
  }
}

/** JSON with sorted keys, to compare stored JWKS regardless of key order. */
function canonical(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>).sort(([a], [b]) =>
      a < b ? -1 : a > b ? 1 : 0,
    );
    return `{${entries.map(([key, item]) => `${JSON.stringify(key)}:${canonical(item)}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

async function ensureApplication(
  repos: Repositories,
  service: SeedService,
): Promise<{ application: Application; created: boolean; secret?: string }> {
  const declared = {
    name: service.name,
    redirectUris: [`${service.url}/auth/callback`],
    postLogoutRedirectUris: [`${service.url}/`],
    representationMode: "optional" as const,
    allowedExtraScopes: [...(service.allowedExtraScopes ?? [])],
  };
  let application = await repos.applications.findByClientId(service.clientId);
  let created = false;
  let generated: string | undefined;
  const jwks = service.jwks;
  if (application === null) {
    generated =
      service.secret === undefined && jwks === undefined ? generateClientSecret() : undefined;
    application = await repos.applications.create({
      clientId: service.clientId,
      clientAuth:
        jwks === undefined
          ? { method: "client_secret_basic", clientSecret: service.secret ?? generated! }
          : { method: "private_key_jwt", jwks },
      ...declared,
    });
    created = true;
  } else if (jwks !== undefined) {
    const current = application.clientAuth;
    const same =
      current.method === "private_key_jwt" &&
      "jwks" in current &&
      canonical(current.jwks) === canonical(jwks);
    application = await repos.applications.update(application.id, {
      ...declared,
      ...(same ? {} : { clientAuth: { method: "private_key_jwt", jwks } }),
    });
  } else {
    const secret = service.secret;
    const secretChanged =
      secret !== undefined && (await repos.applications.getClientSecret(application.id)) !== secret;
    application = await repos.applications.update(application.id, {
      ...declared,
      ...(secretChanged
        ? { clientAuth: { method: "client_secret_basic", clientSecret: secret } }
        : {}),
    });
  }
  for (const role of DEMO_ROLES) {
    await repos.applications.declareRole(application.id, role.role, role.description);
  }
  return { application, created, ...(generated === undefined ? {} : { secret: generated }) };
}
